"""Experiment A analysis: does a lower-width (exact) TD give a cheaper contraction?

    python analyzeA.py <resA dir> [out.md]

Reads resA/td/*.td (exact certificate) and resA/cost/*.tsv (costA.py). Networks enter the exact set when the
EXACT line is certified. Per network and stage (bucket, br, br+ctg, ...):
  gap_w   = TD width - optimal width (bits), gap_c = log10 C - min log10 C over all TD trees of that stage
  rho     = Spearman(width, log10 C) over all TDs of the network; rho_near over TDs with gap_w <= 2
  exact-vs-best-heuristic: min C over width-optimal TDs found by exact solves vs min C over heuristic TDs
  (MF/MF1/AMF/MMD/MCS/bw, random-tiebreak, ND, HBT) -- and vs cotengra hyper 10 s.
  tie-breaking among optimal TDs: C of the exact solver's TD, the median/best/worst optimal TD, and the
  optimal TD chosen by min lcost (log2 sum 2^bag) or min branchstats cost (cost-aware selection).
"""
import glob
import math
import os
import sys
from collections import defaultdict

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import tdfile  # noqa: E402

try:
    from scipy.stats import spearmanr
except ImportError:  # pragma: no cover
    spearmanr = None

STAGES = ["bucket", "bt", "br", "bucket+ctg", "br+ctg"]
EPS = 1e-6


def family(name):
    for p in ("qaoazz", "qaoaamp", "reg", "rqc", "syc", "lat", "mc3sat", "lm_mera"):
        if name.startswith(p):
            return {"lm_mera": "lm"}.get(p, p)
    return name.split("_")[0]


def kind(tag):
    if tag.startswith("exact"):
        return "exact"
    if tag.startswith("hyb"):
        return "hyb"
    if tag.startswith("hbt"):
        return "hbt"
    if tag.startswith("nd"):
        return "nd"
    return "greedy"


def rho(x, y):
    x, y = np.asarray(x), np.asarray(y)
    if len(x) < 4 or np.ptp(x) < EPS or np.ptp(y) < EPS:
        return float("nan")
    return float(spearmanr(x, y).correlation)


def load(resdir):
    nets = {}
    for f in sorted(glob.glob(os.path.join(resdir, "td", "*.td"))):
        td = tdfile.parse(f)
        name = td["net"]["name"]
        cf = os.path.join(resdir, "cost", name + ".tsv")
        if not os.path.exists(cf):
            continue
        rows = defaultdict(dict)   # tag -> stage -> (log10C, W, maxop)
        complete = False
        for line in open(cf):
            if line.startswith("#END"):
                complete = True
            if line.startswith(("#", "net\t")):
                continue
            g = line.rstrip("\n").split("\t")
            rows[g[1]][g[2]] = dict(c=float(g[3]), W=float(g[4]), maxop=float(g[5]), s=float(g[6]),
                                    jl=float(g[9]) if g[9] else float("nan"))
        nets[name] = dict(td=td, rows=rows, complete=complete)
    return nets


def main():
    resdir = sys.argv[1]
    outmd = sys.argv[2] if len(sys.argv) > 2 else os.path.join(resdir, "A_tables.md")
    nets = load(resdir)
    L = []
    P = L.append
    exact = {k: v for k, v in nets.items() if v["td"]["exact"] and v["td"]["exact"]["certified"]}
    P(f"# Experiment A tables (generated by analyzeA.py)\n")
    P(f"networks with cost rows: {len(nets)}; certified exact width: {len(exact)}; "
      f"complete cost files: {sum(v['complete'] for v in nets.values())}\n")

    # consistency of branchstats vs cotengra
    dif = [abs(r["c"] - r["jl"]) for v in nets.values() for t, st in v["rows"].items() for s, r in st.items()
           if s in ("bt", "br") and not math.isnan(r["jl"])]
    if dif:
        P(f"branchstats vs cotengra log10 C: {len(dif)} trees, max |diff| {max(dif):.2e}, "
          f"#>1e-3: {sum(d > 1e-3 for d in dif)}\n")

    per = []   # per network records
    for name, v in sorted(exact.items()):
        td, rows = v["td"], v["rows"]
        opt = td["exact"]["width"]
        meta = {d["tag"]: d for d in td["orders"]}
        rec = dict(name=name, fam=family(name), n=td["net"]["n"], opt=opt, tex=td["exact"]["seconds"])
        for stage in STAGES:
            tags = [t for t in meta if stage in rows.get(t, {})]
            if len(tags) < 4:
                continue
            w = np.array([meta[t]["width"] for t in tags]); c = np.array([rows[t][stage]["c"] for t in tags])
            lc = np.array([meta[t]["lcost"] for t in tags])
            gapw = w - opt
            isopt = gapw <= 1e-6 * max(1.0, opt)
            heur = np.array([kind(t) not in ("exact", "hyb") for t in tags])
            exs = np.array([kind(t) == "exact" for t in tags])
            r = dict(rho=rho(w, c), rho_near=rho(w[gapw <= 2 + EPS], c[gapw <= 2 + EPS]), rho_lcost=rho(lc, c),
                     cmin=c.min(), nopt=int(isopt.sum()), ntd=len(tags))
            r["c_exact0"] = rows["exact"][stage]["c"] if "exact" in rows and stage in rows["exact"] else float("nan")
            r["c_exactbest"] = c[exs].min() if exs.any() else float("nan")
            r["c_opt_best"] = c[isopt].min() if isopt.any() else float("nan")
            r["c_opt_med"] = float(np.median(c[isopt])) if isopt.any() else float("nan")
            r["c_opt_worst"] = c[isopt].max() if isopt.any() else float("nan")
            if isopt.any():
                io = np.where(isopt)[0]
                r["c_opt_bylcost"] = c[io[np.argmin(lc[io])]]
                jl = np.array([meta[t]["br_cost"] for t in tags])   # cost-aware selection by our exact C (br tree)
                r["c_opt_byjl"] = c[io[np.argmin(jl[io])]]
            r["c_heur_best"] = c[heur].min() if heur.any() else float("nan")
            r["w_heur_best"] = w[heur].min() if heur.any() else float("nan")
            hb = np.where(heur)[0]
            # heuristic of min C, and heuristic of min width (ties -> min C)
            r["heur_minC_gapw"] = float(gapw[hb[np.argmin(c[hb])]]) if heur.any() else float("nan")
            # does the cheapest TD-tree overall have optimal width?
            r["argmin_is_opt"] = bool(isopt[np.argmin(c)])
            r["argmin_gapw"] = float(gapw[np.argmin(c)])
            for b in ("ctg_greedy", "ctg_hyper10"):
                st = "+ctg" if stage.endswith("+ctg") else "raw"
                r[b] = rows[b][st]["c"] if b in rows and st in rows[b] else float("nan")
            rec[stage] = r
        per.append(rec)

    def med(xs):
        xs = [x for x in xs if not (isinstance(x, float) and math.isnan(x))]
        return (float(np.median(xs)), len(xs)) if xs else (float("nan"), 0)

    P("## 1. Rank correlation width vs log10 C (Spearman, per network; median over networks)\n")
    P("| stage | all TDs | TDs within 2 bits of opt | lcost vs C | #nets |")
    P("|---|---|---|---|---|")
    for stage in STAGES:
        rs = [p[stage] for p in per if stage in p]
        a, n = med([r["rho"] for r in rs]); b, _ = med([r["rho_near"] for r in rs]); c, _ = med([r["rho_lcost"] for r in rs])
        P(f"| {stage} | {a:.2f} | {b:.2f} | {c:.2f} | {n} |")
    P("")
    P("## 2. Is width-optimal also cost-optimal? (over all TDs we generated)\n")
    P("| stage | cheapest TD-tree has optimal width | median width gap of the cheapest (bits) | max | "
      "exact(best of relabels) vs best heuristic: W/T/L (|d|<0.01) | median d log10C | worst d | "
      "exact solver's own TD vs best heuristic: median d |")
    P("|---|---|---|---|---|---|---|---|")
    for stage in STAGES:
        rs = [p[stage] for p in per if stage in p]
        if not rs:
            continue
        k = sum(r["argmin_is_opt"] for r in rs)
        gaps = [r["argmin_gapw"] for r in rs]
        d = np.array([r["c_exactbest"] - r["c_heur_best"] for r in rs])
        d0 = np.array([r["c_exact0"] - r["c_heur_best"] for r in rs])
        d = d[~np.isnan(d)]; d0 = d0[~np.isnan(d0)]
        w = int((d < -0.01).sum()); t = int((abs(d) <= 0.01).sum()); l_ = int((d > 0.01).sum())
        P(f"| {stage} | {k}/{len(rs)} | {np.median(gaps):.2f} | {max(gaps):.2f} | {w}/{t}/{l_} | "
          f"{np.median(d):+.3f} | {d.max():+.3f} | {np.median(d0):+.3f} |")
    P("\nd = log10 C(exact) - log10 C(best heuristic TD); negative = exact cheaper.\n")

    P("## 3. Tie-breaking among width-optimal TDs (stage br+ctg and bucket)\n")
    P("| stage | nets with >=2 optimal TDs | median #optimal TDs | median spread worst-best (log10 C) | max spread | "
      "exact solver TD - best opt | by-lcost - best opt | by-our-C - best opt | best opt - best heuristic |")
    P("|---|---|---|---|---|---|---|---|---|")
    for stage in ("bucket", "br", "br+ctg"):
        rs = [p[stage] for p in per if stage in p and p[stage]["nopt"] >= 2]
        if not rs:
            continue
        sp = [r["c_opt_worst"] - r["c_opt_best"] for r in rs]
        e0 = [r["c_exact0"] - r["c_opt_best"] for r in rs]
        bl = [r["c_opt_bylcost"] - r["c_opt_best"] for r in rs]
        bj = [r["c_opt_byjl"] - r["c_opt_best"] for r in rs]
        bh = [r["c_opt_best"] - r["c_heur_best"] for r in rs]
        P(f"| {stage} | {len(rs)} | {np.median([r['nopt'] for r in rs]):.0f} | {np.nanmedian(sp):.3f} | {np.nanmax(sp):.3f} | "
          f"{np.nanmedian(e0):.3f} | {np.nanmedian(bl):.3f} | {np.nanmedian(bj):.3f} | {np.nanmedian(bh):+.3f} |")
    P("")

    P("## 4. Per family (stage br+ctg): median rho, exact-vs-best-heuristic d, best TD-tree vs cotengra hyper 10 s\n")
    P("| family | nets | rho all | rho near | cheapest has opt width | median d(exact-heur) | median (best TD - ctg hyper10) |")
    P("|---|---|---|---|---|---|---|")
    fams = defaultdict(list)
    for p in per:
        if "br+ctg" in p:
            fams[p["fam"]].append(p["br+ctg"])
    for fam, rs in sorted(fams.items()):
        P(f"| {fam} | {len(rs)} | {med([r['rho'] for r in rs])[0]:.2f} | {med([r['rho_near'] for r in rs])[0]:.2f} | "
          f"{sum(r['argmin_is_opt'] for r in rs)}/{len(rs)} | {med([r['c_exactbest'] - r['c_heur_best'] for r in rs])[0]:+.3f} | "
          f"{med([r['cmin'] - r['ctg_hyper10'] for r in rs])[0]:+.3f} |")
    P("")

    P("## 5. Per network (stage br+ctg)\n")
    P("| net | n | opt width | exact s | #TD | #opt | rho | C exact solver | C best opt | C best heur (gap_w of it) | ctg hyper10 |")
    P("|---|---|---|---|---|---|---|---|---|---|---|")
    for p in sorted(per, key=lambda p: (p["fam"], p["n"])):
        r = p.get("br+ctg")
        if not r:
            continue
        P(f"| {p['name']} | {p['n']} | {p['opt']:.2f} | {p['tex']:.1f} | {r['ntd']} | {r['nopt']} | {r['rho']:.2f} | "
          f"{r['c_exact0']:.3f} | {r['c_opt_best']:.3f} | {r['c_heur_best']:.3f} ({r['heur_minC_gapw']:.1f}) | {r['ctg_hyper10']:.3f} |")
    P("")
    nonex = [k for k, v in nets.items() if k not in exact]
    P(f"## 6. Not certified within the exact budget ({len(nonex)}): "
      + ", ".join(f"{k} [{nets[k]['td']['exact']['lower']:.1f},{nets[k]['td']['exact']['width']:.1f}]"
                  for k in sorted(nonex) if nets[k]['td']['exact']) + "\n")
    open(outmd, "w").write("\n".join(L) + "\n")
    print("\n".join(L[:60]))

    # plot data: width gap vs cost gap, one point per (network, TD), stage br+ctg and bucket
    with open(os.path.join(resdir, "A_points.tsv"), "w") as f:
        f.write("net\tfam\ttag\tkind\tstage\tgap_w\tgap_c\tlog10C\twidth\n")
        for name, v in exact.items():
            td, rows = v["td"], v["rows"]; opt = td["exact"]["width"]
            for stage in STAGES:
                cs = [rows[d["tag"]][stage]["c"] for d in td["orders"] if stage in rows.get(d["tag"], {})]
                if not cs:
                    continue
                cmin = min(cs)
                for d in td["orders"]:
                    if stage in rows.get(d["tag"], {}):
                        c = rows[d["tag"]][stage]["c"]
                        f.write(f"{name}\t{family(name)}\t{d['tag']}\t{kind(d['tag'])}\t{stage}\t{d['width'] - opt:.4f}\t"
                                f"{c - cmin:.4f}\t{c:.4f}\t{d['width']:.4f}\n")


if __name__ == "__main__":
    main()
