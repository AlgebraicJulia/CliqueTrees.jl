"""Experiment B analysis: predicted C vs real B200 contraction time, ours vs cotengra, time to solution.

    python analyzeB.py <resB dir> [out.md]

Reads resB/gpu_torch.tsv (contractB.py) and, if present, resB/gpu_cutn.tsv (contract_cutn.py).
"""
import math
import os
import sys
from collections import defaultdict

import numpy as np

try:
    from scipy.stats import spearmanr, pearsonr
except ImportError:  # pragma: no cover
    spearmanr = pearsonr = None


def read(path):
    rows = []
    if not os.path.exists(path):
        return rows
    hdr = None
    for line in open(path):
        f = line.rstrip("\n").split("\t")
        if f[0] == "net":
            hdr = f
            continue
        rows.append(dict(zip(hdr, f)))
    return rows


def fl(x):
    try:
        return float(x)
    except (TypeError, ValueError):
        return float("nan")


def main():
    res = sys.argv[1]
    outmd = sys.argv[2] if len(sys.argv) > 2 else os.path.join(res, "B_tables.md")
    rows = [r for r in read(os.path.join(res, "gpu_torch.tsv")) if r.get("status") == "ok"]
    allrows = read(os.path.join(res, "gpu_torch.tsv"))
    L = []; P = L.append
    P("# Experiment B tables (generated by analyzeB.py)\n")
    P(f"executed trees: {len(rows)} ok of {len(allrows)} rows; networks: {len({r['net'] for r in rows})}; "
      f"status counts: { {s: sum(r['status'] == s for r in allrows) for s in {r['status'] for r in allrows}} }\n")
    errs = [fl(r["relerr"]) for r in rows]
    P(f"numerical agreement (rel. 2-norm diff to the complex128 / first result): median {np.median(errs):.1e}, "
      f"max {np.max(errs):.1e}, #>1e-3: {sum(e > 1e-3 for e in errs)}\n")

    c = np.array([fl(r["log10C"]) for r in rows]); t = np.array([fl(r["t_med"]) for r in rows])
    nc = np.array([fl(r["ncontract"]) for r in rows])
    lt = np.log10(t)
    P("## 1. Predicted C vs real time\n")
    P(f"- pooled over all (network, tree): Spearman(log10 C, log10 t) = {spearmanr(c, lt).correlation:.3f}, "
      f"Pearson = {pearsonr(c, lt)[0]:.3f} (n={len(c)})")
    big = c >= 10
    if big.sum() > 3:
        P(f"- trees with log10 C >= 10: Spearman = {spearmanr(c[big], lt[big]).correlation:.3f} (n={big.sum()})")
    # time model t = a * ncontract + b * C  (least squares on relative error via weights 1/t)
    A = np.vstack([nc, 10 ** c]).T / t[:, None]
    coef, *_ = np.linalg.lstsq(A, np.ones_like(t), rcond=None)
    pred = np.vstack([nc, 10 ** c]).T @ coef
    P(f"- model t = a*#pairwise + b*C: a = {coef[0] * 1e6:.1f} us, b = {coef[1] * 1e12:.3f} ps/MAC "
      f"(= {1 / max(coef[1], 1e-30) / 1e12 * 8:.1f} TFLOP/s complex64 effective); median |rel err| "
      f"{np.median(abs(pred - t) / t):.2f}")
    bynet = defaultdict(list)
    for r in rows:
        bynet[r["net"]].append(r)
    within = []
    for net, rs in bynet.items():
        x = [fl(r["log10C"]) for r in rs]; y = [fl(r["t_med"]) for r in rs]
        if len(rs) >= 4 and np.ptp(x) > 0.05:
            within.append(spearmanr(x, y).correlation)
    if within:
        P(f"- within-network Spearman (networks whose trees differ by > 0.05 in log10 C): median {np.median(within):.2f}, "
          f"min {np.min(within):.2f} over {len(within)} networks")
    # how often does the lower-C tree win in real time, pairwise within a network
    agree = tot = 0
    for net, rs in bynet.items():
        for i in range(len(rs)):
            for j in range(i + 1, len(rs)):
                dc = fl(rs[i]["log10C"]) - fl(rs[j]["log10C"]); dt = math.log10(fl(rs[i]["t_med"]) / fl(rs[j]["t_med"]))
                if abs(dc) >= 0.1:
                    tot += 1; agree += (dc > 0) == (dt > 0)
    if tot:
        P(f"- pairs of trees of one network with |d log10 C| >= 0.1: lower-C tree is faster in {agree}/{tot} ({agree / tot:.0%})")
    P("")

    P("## 2. Per network (B200, torch complex64, warm median of 3)\n")
    tags = ["ours10", "ours60", "ctg_hyper10", "ctg_hyper60", "td_MF1", "td_hbt1", "td_exact", "ctg_greedy"]
    P("| net | " + " | ".join(tags) + " | ours60/hyper60 time | ours60/hyper60 C |")
    P("|---|" + "---|" * (len(tags) + 2))
    W = defaultdict(lambda: [0, 0, 0])
    tts = defaultdict(list)
    for net in sorted(bynet, key=lambda n: min(fl(r["log10C"]) for r in bynet[n])):
        d = {r["tag"].replace("td_hyb300", "td_exact"): r for r in bynet[net]}
        cells = []
        for tg in tags:
            r = d.get(tg)
            cells.append(f"{fl(r['log10C']):.2f} / {fl(r['t_med']):.3g}s" if r else "-")
        ratio_t = ratio_c = "-"
        if "ours60" in d and "ctg_hyper60" in d:
            rt = fl(d["ours60"]["t_med"]) / fl(d["ctg_hyper60"]["t_med"])
            rc = 10 ** (fl(d["ours60"]["log10C"]) - fl(d["ctg_hyper60"]["log10C"]))
            ratio_t, ratio_c = f"{rt:.2f}", f"{rc:.2f}"
        P(f"| {net} | " + " | ".join(cells) + f" | {ratio_t} | {ratio_c} |")
        for a, b in (("ours10", "ctg_hyper10"), ("ours60", "ctg_hyper60"), ("td_exact", "td_MF1"), ("td_exact", "td_hbt1"),
                     ("td_exact", "ctg_hyper60")):
            if a in d and b in d:
                rt = fl(d[a]["t_med"]) / fl(d[b]["t_med"])
                k = 0 if rt < 0.95 else (1 if rt <= 1.05 else 2)
                W[(a, b)][k] += 1
                tts[(a, b)].append((fl(d[a]["search_s"]) + fl(d[a]["t_med"])) / (fl(d[b]["search_s"]) + fl(d[b]["t_med"])))
                tts[(a, b, "c")].append(fl(d[a]["log10C"]) - fl(d[b]["log10C"]))
                tts[(a, b, "t")].append(math.log10(rt))
    nh = sum(r["tag"] == "td_hyb300" for r in rows)
    P(f"\ncells: log10 C (predicted, cotengra) / measured seconds. td_exact includes {nh} networks whose exact solve "
      "was NOT certified in 300 s (tag td_hyb300: best TD found, width not proven optimal).\n")
    P("## 3. Head to head (real time, ±5% = tie)\n")
    P("| A vs B | A faster / tie / slower | median log10 C(A)-C(B) | median log10 t(A)/t(B) | median time-to-solution ratio (search + 1 contraction) |")
    P("|---|---|---|---|---|")
    for k, v in W.items():
        P(f"| {k[0]} vs {k[1]} | {v[0]}/{v[1]}/{v[2]} | {np.median(tts[k + ('c',)]):+.3f} | {np.median(tts[k + ('t',)]):+.3f} | "
          f"{np.median(tts[k]):.2f} |")
    P("")
    cut = read(os.path.join(res, "gpu_cutn.tsv"))
    if cut:
        P("## 4. cuTensorNet (executor for all paths + its own path finder)\n")
        P("| net | tag | pred log10C | search s | t_med s | status |")
        P("|---|---|---|---|---|---|")
        for r in cut:
            P(f"| {r['net']} | {r['tag']} | {r['log10C_pred']} | {r['search_s']} | {r['t_med']} | {r['status'][:40]} |")
    open(outmd, "w").write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
