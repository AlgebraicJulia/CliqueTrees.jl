#!/usr/bin/env python3
"""Merge HPG results into parallel_baselines.tsv and rebuild PARALLEL_SUMMARY.md.
usage (from this directory):  ./make_parallel_summary.py [--fetch]
  --fetch : first scp /blue/fairbanksj/itaykadosh/gpu/pbase/res/{paramd,pmetis,serial}-*.tsv from HPG (ssh alias hpg)
"""
import csv, glob, os, subprocess, sys, statistics as st
here = os.path.dirname(os.path.abspath(__file__))
os.chdir(here)
if "--fetch" in sys.argv:
    os.makedirs("pbase_res", exist_ok=True)
    subprocess.check_call("scp 'hpg:/blue/fairbanksj/itaykadosh/gpu/pbase/res/*.tsv' pbase_res/", shell=True)
cols = "host graph n edges method threads nnzL flops width time_s status".split()
rows = []
for f in sorted(glob.glob("pbase_res/*.tsv")):
    if os.path.basename(f).startswith("smoke"): continue
    for l in open(f):
        p = l.rstrip("\n").split("\t")
        if len(p) == 11: rows.append(dict(zip(cols, p)))
with open("parallel_baselines.tsv", "w") as o:
    o.write("\t".join(cols + ["platform"]) + "\n")
    for r in rows:
        o.write("\t".join(r[c] for c in cols) + "\tmilan(hpg-milan)\n")
# reference data
mt = {}; nn = {}
for r in csv.DictReader(open("main_table.tsv"), delimiter="\t"):
    nn[r["graph"]] = int(r["n"]); mt.setdefault(r["graph"], {})[r["cfg"]] = r
def get(g, cfg):
    r = mt.get(g, {}).get(cfg)
    return None if r is None else (float(r["nnzL"]), float(r["flops"]), float(r["time_s"]))
def ens(g):
    for k in ("GPU-MF1-ens8", "GPU-MF1-ens4", "GPU-MF1-ens2"):
        v = get(g, k)
        if v: return v
REF = "serial-MF1-new(rmain)"
pb = {}
for r in rows:
    if r["status"] == "ok" and r["nnzL"]:
        pb[(r["graph"], r["method"], int(r["threads"]))] = (float(r["nnzL"]), float(r["flops"]), float(r["time_s"]))
sources = [
    ("serial MF1 (ref)", lambda g: get(g, REF)),
    ("GPU-MF1 u0.1", lambda g: get(g, "GPU-MF1-u0.1")),
    ("GPU-MF1 fast (v2)", lambda g: get(g, "GPU-MF1-fastest(rr/v2 same fill)")),
    ("GPU-MF1 ens", ens),
    ("ParAMD t64", lambda g: pb.get((g, "PARAMD", 64))),
    ("ParMETIS-ND t64 (mt-metis substitute)", lambda g: pb.get((g, "PARMETIS", 64))),
    ("AMD (serial)", lambda g: pb.get((g, "AMD", 1))),
    ("METIS-ND (serial)", lambda g: pb.get((g, "METIS", 1))),
]
buckets = [("<100k", 0, 100_000), ("100k-1M", 100_000, 1_000_000), ("1-3M", 1_000_000, 3_000_000), (">=3M", 3_000_000, 10**12)]
def med(x): return f"{st.median(x):.3g}" if x else "-"
out = []
out.append("""# Parallel CPU ordering baselines vs GPU-MF1 (PARALLEL_SUMMARY)

Graph set: the 44 graphs of main_table.tsv (the task said 47; main_table has 44 distinct graphs, rndhyp/mc3sat rows are absent from it). Unit weights.
Metrics: nnz(L) incl. diagonal, flops, width computed exactly as rport/sbench.jl `fillq` (cliquetree supernodes), validity asserted by `isperm`.
Time = min of 3 runs for n<1M, 1 run for n>=1M. Ratios = per-graph value / new serial MF1 (rmain, main_table), then median over graphs having both rows (count `k`). Tables are generated by `make_parallel_summary.py`.

## Methods and caveats
- **ParAMD** (built paramd, `--mult 1.1 --lim 8192 --mem 3.0 --seed 1`, OMP_PROC_BIND=close, OMP_PLACES=cores), threads 1/8/32/64. NOT run with `--sym`: this build segfaults with `--sym` on non-lattice graphs (bcsstk17, thermal1), so ParAMD symmetrizes internally and that is inside its timed region. Its time excludes file reading and the random pre-permutation.
- **mt-metis: not built.** Every upstream source location returned 404 from HPG (github.com/dlasalle/mt-metis, bitbucket dlasalle/mt-metis, glaros.dtc.umn.edu tarball); no spec-only mirror has sources. Substituted **ParMETIS 4.0.3 `ParMETIS_V3_NodeND`** (distributed-memory MPI nested dissection, built from the Karypis tarball, 32-bit idx) with 1/8/32/64 MPI ranks on one node. Rank 1 = serial METIS ND. This is a different algorithm family than mt-metis (distributed, coarser quality, MPI overhead); time = barrier-to-barrier around the call (excludes input read and gather). No PT-Scotch.
- **AMD, METIS-ND serial**: CliqueTrees rmain (598b013) `AMD()` / `METIS()` via `using AMD, Metis` (the old failure was a missing import), min of 3 / 1.
- Self loops are stripped for ParAMD/ParMETIS inputs; AMD/METIS-ND get the same SimpleGraph as the main_table evaluator.
- **Platform**: baselines run on hpg-milan (AMD EPYC, node shared, NOT --exclusive, so t32/t64 and memory-bandwidth timings may see neighbour noise; hostname and lscpu are in each job log). GPU-MF1 rows are B200 (host CPU is not milan), serial MF1 is one milan core. The GPU-MF1 time is device time on B200 while ParAMD/ParMETIS use 64 CPU cores: a platform comparison, not equal-silicon.
- Rows with status `timeout` (per-run cap 1500 s), `crash` or `rcN` are kept in parallel_baselines.tsv and ignored in the tables.

## How to harvest
```
cd ~/Projects/GATAS/tn-work/harvest_oct19b/mf
./make_parallel_summary.py --fetch     # scp HPG res/*.tsv -> pbase_res/, rewrite parallel_baselines.tsv and this file
```
HPG jobs (code and logs in /blue/fairbanksj/itaykadosh/gpu/pbase: pbench.jl, pnd.c, pb_*.sbatch, res/, logs/): see JOBS below. Results append per (graph, method, threads) in ascending graph size, so partial output is usable while a job runs (the largest graphs come last).

JOBS (hpg-milan, 64 cpus, 4 h): pb-paramd-small, pb-paramd-large, pb-pmetis-small, pb-pmetis-large (n<1M / n>=1M each), pb-serial (AMD and METIS-ND, 8 cpus). Job ids are in the final report of the session that submitted them: 46781984 paramd-small, 46781985 paramd-large, 46781986 pmetis-small, 46781987 pmetis-large, 46781988 serial. The old ParAMD job 46726920 was cancelled.
""")
out.append(f"Rows loaded: {len(rows)} ({sum(1 for r in rows if r['status']=='ok')} ok).\n")
for bn, lo, hi in buckets:
    gs = [g for g in nn if lo <= nn[g] < hi]
    out.append(f"\n## Bucket {bn} ({len(gs)} graphs)\n")
    out.append("| method | k | median time s | median nnz(L) / MF1 | median flops / MF1 |\n|---|---|---|---|---|")
    for name, fn in sources:
        t, a, b, k = [], [], [], 0
        for g in gs:
            v = fn(g); r = get(g, REF)
            if v is None: continue
            t.append(v[2])
            if r: a.append(v[0] / r[0]); b.append(v[1] / r[1]); k += 1
        out.append(f"| {name} | {len(t)} | {med(t)} | {med(a)} | {med(b)} |")
out.append("\n## Thread scaling (median time s over graphs with all four thread counts, per bucket)\n")
out.append("| method | bucket | k | t1 | t8 | t32 | t64 |\n|---|---|---|---|---|---|---|")
for meth in ("PARAMD", "PARMETIS"):
    for bn, lo, hi in buckets:
        gs = [g for g in nn if lo <= nn[g] < hi and all((g, meth, t) in pb for t in (1, 8, 32, 64))]
        out.append(f"| {meth} | {bn} | {len(gs)} | " + " | ".join(med([pb[(g, meth, t)][2] for g in gs]) for t in (1, 8, 32, 64)) + " |")
bad = [r for r in rows if r["status"] != "ok"]
out.append(f"\n## Failed rows: {len(bad)}\n")
for r in bad[:40]: out.append(f"- {r['graph']} {r['method']} t{r['threads']}: {r['status']}")
# sanity: edge counts vs main_table
mm = {}
for r in csv.DictReader(open("main_table.tsv"), delimiter="\t"): mm[r["graph"]] = r["edges"]
chk = sorted({r["graph"] for r in rows if mm.get(r["graph"]) and mm[r["graph"]] != r["edges"]})
out.append(f"\nEdge-count mismatches vs main_table: {chk if chk else 'none'}\n")
open("PARALLEL_SUMMARY.md", "w").write("\n".join(out))
print("wrote PARALLEL_SUMMARY.md, parallel_baselines.tsv")
